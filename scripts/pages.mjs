/**
 * GitHub Pages build for the phone-friendly website.
 *
 *   node scripts/pages.mjs build     static export into ./out-pages + offline service worker
 *   node scripts/pages.mjs preview   build, then serve it at http://localhost:4173/glyphx/ (also on your Wi-Fi)
 *   node scripts/pages.mjs serve     serve the existing ./out-pages build without rebuilding
 *   node scripts/pages.mjs publish   build, then force-push ./out-pages to the repository's gh-pages branch
 *
 * The site lives at https://<user>.github.io/glyphx/ — keep BASE in sync with
 * PAGES_BASE_PATH in next.config.ts (it must match the repository name).
 */
import { spawnSync } from "node:child_process";
import { createHash } from "node:crypto";
import { existsSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from "node:fs";
import { createServer } from "node:http";
import { networkInterfaces } from "node:os";
import { extname, join, normalize, relative, sep } from "node:path";

const BASE = "/glyphx";
const OUT = "out-pages";
const PORT = Number(process.env.PORT || 4173);
const isWin = process.platform === "win32";
const mode = process.argv[2] ?? "build";

function run(cmd, args, { env = {}, cwd, capture = false } = {}) {
  const useShell = isWin && cmd === "npx"; // npx is a .cmd shim on Windows
  const res = useShell
    ? spawnSync([cmd, ...args].join(" "), { shell: true, cwd, stdio: capture ? "pipe" : "inherit", env: { ...process.env, ...env } })
    : spawnSync(cmd, args, { cwd, stdio: capture ? "pipe" : "inherit", env: { ...process.env, ...env } });
  if (res.status !== 0) {
    if (capture) process.stderr.write(res.stderr?.toString() ?? "");
    process.exit(res.status ?? 1);
  }
  return capture ? res.stdout.toString().trim() : "";
}

function walk(dir) {
  return readdirSync(dir, { withFileTypes: true }).flatMap((d) => {
    const p = join(dir, d.name);
    return d.isDirectory() ? walk(p) : [p];
  });
}

/** Service worker: precache the whole site, network-first for pages, cache-first for hashed assets. */
function writeServiceWorker() {
  const files = walk(OUT)
    .map((f) => relative(OUT, f).split(sep).join("/"))
    .filter((f) => !f.endsWith(".txt") && f !== "sw.js" && f !== ".nojekyll" && !f.startsWith("_not-found/") && !f.startsWith(".git/"))
    .sort();
  const urls = files.map((f) => `${BASE}/${f.replace(/(^|\/)index\.html$/, "$1")}`);
  const hash = createHash("sha256");
  for (const f of files) hash.update(f).update(readFileSync(join(OUT, f)));
  const version = hash.digest("hex").slice(0, 12);

  const sw = `/* GlyphX offline cache — generated by scripts/pages.mjs. Do not edit. */
const BASE = ${JSON.stringify(BASE)};
const CACHE = "glyphx-${version}";
const PRECACHE = ${JSON.stringify(urls)};

self.addEventListener("install", (event) => {
  event.waitUntil(caches.open(CACHE).then((cache) => cache.addAll(PRECACHE)).then(() => self.skipWaiting()));
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith("glyphx-") && k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

async function remember(request, response) {
  if (response.ok && response.type === "basic") {
    const cache = await caches.open(CACHE);
    await cache.put(request, response.clone());
  }
  return response;
}

self.addEventListener("fetch", (event) => {
  const request = event.request;
  if (request.method !== "GET") return;
  const url = new URL(request.url);
  if (url.origin !== self.location.origin || !url.pathname.startsWith(BASE + "/")) return;

  // Pages and router payloads: fresh when online, cached copy when offline.
  if (request.mode === "navigate" || url.pathname.endsWith(".txt")) {
    event.respondWith(
      fetch(request)
        .then((response) => remember(request, response))
        .catch(async () => (await caches.match(request, { ignoreSearch: true })) || (await caches.match(BASE + "/")) || Response.error()),
    );
    return;
  }

  // Hashed scripts, styles, fonts and icons never change for a given URL.
  event.respondWith(caches.match(request).then((hit) => hit || fetch(request).then((response) => remember(request, response))));
});
`;
  writeFileSync(join(OUT, "sw.js"), sw);
  const bytes = files.reduce((n, f) => n + statSync(join(OUT, f)).size, 0);
  console.log(`Service worker: ${urls.length} files precached (${(bytes / 1024 / 1024).toFixed(1)} MB), cache glyphx-${version}`);
}

function build() {
  run("npx", ["next", "build"], { env: { GLYPHX_TARGET: "pages" } });
  if (!existsSync(join(OUT, "index.html"))) {
    console.error(`Static export failed: ${OUT}/index.html is missing.`);
    process.exit(1);
  }
  // Without this, GitHub Pages runs Jekyll, which drops the _next folder.
  writeFileSync(join(OUT, ".nojekyll"), "");
  writeServiceWorker();
}

const MIME = {
  ".html": "text/html; charset=utf-8",
  ".js": "text/javascript; charset=utf-8",
  ".css": "text/css; charset=utf-8",
  ".txt": "text/plain; charset=utf-8",
  ".json": "application/json",
  ".webmanifest": "application/manifest+json",
  ".png": "image/png",
  ".ico": "image/x-icon",
  ".woff2": "font/woff2",
};

/** Minimal static server that behaves like GitHub Pages for a project site. */
function preview() {
  const server = createServer((req, res) => {
    const { pathname } = new URL(req.url ?? "/", "http://localhost");
    if (pathname === "/" || pathname === BASE) {
      res.writeHead(301, { location: `${BASE}/` }).end();
      return;
    }
    if (!pathname.startsWith(`${BASE}/`)) {
      res.writeHead(404).end("Not found");
      return;
    }
    let rel = decodeURIComponent(pathname.slice(BASE.length));
    if (rel.endsWith("/")) rel += "index.html";
    const root = normalize(OUT);
    let file = normalize(join(root, rel));
    if (!file.startsWith(root)) {
      res.writeHead(403).end();
      return;
    }
    if (!extname(file) && existsSync(join(file, "index.html"))) {
      res.writeHead(301, { location: `${pathname}/` }).end();
      return;
    }
    let status = 200;
    if (!existsSync(file) || statSync(file).isDirectory()) {
      file = join(root, "404.html");
      status = 404;
    }
    res.writeHead(status, { "content-type": MIME[extname(file)] ?? "application/octet-stream", "cache-control": "no-cache" });
    res.end(readFileSync(file));
  });
  server.listen(PORT, () => {
    console.log(`GlyphX website preview: http://localhost:${PORT}${BASE}/`);
    for (const list of Object.values(networkInterfaces())) {
      for (const a of list ?? []) {
        if (a.family === "IPv4" && !a.internal) console.log(`On your phone (same Wi-Fi): http://${a.address}:${PORT}${BASE}/`);
      }
    }
  });
}

function publish() {
  const remote = run("git", ["remote", "get-url", "origin"], { capture: true });
  const name = run("git", ["config", "user.name"], { capture: true });
  const email = run("git", ["config", "user.email"], { capture: true });
  const dirty = run("git", ["status", "--porcelain"], { capture: true }) !== "";
  const source = run("git", ["rev-parse", "--short", "HEAD"], { capture: true }) + (dirty ? " with uncommitted changes" : "");
  rmSync(join(OUT, ".git"), { recursive: true, force: true });
  const git = (...args) => run("git", ["-c", `user.name=${name}`, "-c", `user.email=${email}`, ...args], { cwd: OUT });
  git("init", "-q", "-b", "gh-pages");
  git("add", "-A");
  git(
    "commit",
    "-q",
    "-m",
    `Deploy GlyphX website from ${source}\n\nCo-Authored-By: Claude Opus 5.5 <noreply@anthropic.com>`,
  );
  // The gh-pages branch only ever holds the latest build, so it is replaced on every publish.
  git("push", "-f", remote, "gh-pages");
  rmSync(join(OUT, ".git"), { recursive: true, force: true });
  console.log(`Published ${OUT} to the gh-pages branch of ${remote}`);
}

switch (mode) {
  case "build":
    build();
    break;
  case "preview":
    build();
    preview();
    break;
  case "serve":
    preview();
    break;
  case "publish":
    build();
    publish();
    break;
  default:
    console.error(`Unknown mode "${mode}". Use build, preview, serve or publish.`);
    process.exit(1);
}
