r"""Generate src/lib/unicode/names.generated.ts from Python's unicodedata.

The table covers the blocks GlyphX produces or lets users pick from. It is
loaded lazily by the inspector, so it never weighs on the initial bundle.
Usage: python scripts/generate-names.py
"""
import unicodedata, json, os

RANGES = [
    (0x0020, 0x007E), (0x00A0, 0x024F), (0x0250, 0x02FF), (0x0300, 0x036F), (0x0370, 0x03FF),
    (0x0400, 0x04FF), (0x0E3F, 0x0E3F),     (0x16A0, 0x16FF), (0x1AB0, 0x1AFF), (0x1D00, 0x1DBF), (0x1DC0, 0x1DFF), (0x2000, 0x206F),
    (0x2070, 0x209F), (0x20A0, 0x20CF), (0x20D0, 0x20FF), (0x2100, 0x214F), (0x2150, 0x218F),
    (0x2190, 0x21FF), (0x2200, 0x22FF), (0x2300, 0x23FF), (0x2460, 0x24FF), (0x2500, 0x257F),
    (0x2580, 0x259F), (0x25A0, 0x25FF), (0x2600, 0x26FF), (0x2700, 0x27BF), (0x27C0, 0x27EF),
    (0x27F0, 0x27FF), (0x2800, 0x2800), (0x2900, 0x297F), (0x2980, 0x29FF), (0x2B00, 0x2BFF), (0x2C60, 0x2C7F),
    (0x2E00, 0x2E7F), (0x3000, 0x303F), (0x3040, 0x30FF), (0x3100, 0x312F), (0x3164, 0x3164),
    (0xA4D0, 0xA4FF), (0xA720, 0xA7FF), (0xAB30, 0xAB6F), (0xFE00, 0xFE0F), (0xFE20, 0xFE2F),
    (0xFF01, 0xFF9F), (0xFFFD, 0xFFFD), (0x1F000, 0x1F02F), (0x1F0A0, 0x1F0FF), (0x1F100, 0x1F1FF),
    (0x1F200, 0x1F2FF), (0x1F300, 0x1F5FF), (0x1F600, 0x1F64F), (0x1F680, 0x1F6FF), (0x1F780, 0x1F7FF),
    (0x1F900, 0x1F9FF), (0x1FA70, 0x1FAFF), (0xE0020, 0xE007F),
]
# A few CJK ideographs used by the Kanji-style font and nickname decorations
EXTRA = [ord(c) for c in "卂乃匚乇千卄丨爪几卩尺丂山乂乙亗么乛〆彡ልጌርዕቿቻኗዘጎጋጕረጠክዐየዒዪነፕሁሀሠሸሃጊᐯᄅᎮᏟ"] + [0x115F, 0x1160]

entries = []
seen = set()
for a, b in RANGES:
    for cp in range(a, b + 1):
        name = unicodedata.name(chr(cp), "")
        if name and cp not in seen:
            seen.add(cp)
            entries.append("%X:%s" % (cp, name))
for cp in EXTRA:
    if cp not in seen:
        seen.add(cp)
        entries.append("%X:%s" % (cp, unicodedata.name(chr(cp), "CJK UNIFIED IDEOGRAPH-%X" % cp)))

out = os.path.join(os.path.dirname(__file__), "..", "src", "lib", "unicode", "names.generated.ts")
with open(out, "w", encoding="utf-8", newline="\n") as f:
    f.write("// Generated by scripts/generate-names.py from Unicode %s data. Do not edit.\n" % unicodedata.unidata_version)
    f.write("export const UNICODE_VERSION = %s;\n" % json.dumps(unicodedata.unidata_version))
    f.write("export const NAME_TABLE = %s;\n" % json.dumps("|".join(entries)))
print(len(entries), "names written")
